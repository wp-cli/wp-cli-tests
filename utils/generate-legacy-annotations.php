<?php
/**
 * Generate the annotations that stand in for the attributes of the step definitions and hooks.
 *
 * The contexts declare their steps and hooks with attributes, which is all Behat 4 reads. PHP 7 has
 * no attributes, and the Behat 3 releases that run on it only know annotations, so those get the
 * same declarations as annotations on an interface, see src/Context/LegacyAnnotations.php.
 *
 * Needs PHP 8.1 or later, with a Behat that has all the attributes.
 *
 * Usage: php utils/generate-legacy-annotations.php [--check]
 */

use Behat\Hook\AfterSuite;
use Behat\Hook\BeforeSuite;
use Behat\Hook\Hook;
use Behat\Step\Definition;
use WP_CLI\Tests\Context\FeatureContext;

/**
 * Render a type the way PHP 7.2 can read it.
 *
 * @param ReflectionType|null $type
 * @return string
 */
function wp_cli_tests_legacy_type( $type ) {
	if ( null === $type ) {
		return '';
	}

	if ( ! $type instanceof ReflectionNamedType ) {
		throw new RuntimeException( "Type {$type} cannot be declared in PHP 7.2." );
	}

	$name = $type->getName();

	if ( in_array( $name, [ 'mixed', 'static', 'never', 'null', 'false', 'true' ], true ) ) {
		throw new RuntimeException( "Type {$name} cannot be declared in PHP 7.2." );
	}

	return ( $type->allowsNull() ? '?' : '' ) . ( $type->isBuiltin() ? '' : '\\' ) . $name;
}

/**
 * Render the declaration of a method, without a body.
 *
 * @param ReflectionMethod $method
 * @return string
 */
function wp_cli_tests_legacy_signature( ReflectionMethod $method ) {
	$parameters = [];

	foreach ( $method->getParameters() as $parameter ) {
		if ( $parameter->isVariadic() || $parameter->isPassedByReference() ) {
			throw new RuntimeException( "Parameter \${$parameter->getName()} of {$method->getName()}() is not supported." );
		}

		$declaration = trim( wp_cli_tests_legacy_type( $parameter->getType() ) . ' $' . $parameter->getName() );

		if ( $parameter->isDefaultValueAvailable() ) {
			$declaration .= ' = ' . strtolower( var_export( $parameter->getDefaultValue(), true ) );
		}

		$parameters[] = $declaration;
	}

	$return = wp_cli_tests_legacy_type( $method->getReturnType() );

	return 'public ' . ( $method->isStatic() ? 'static ' : '' ) . "function {$method->getName()}("
		. ( $parameters ? ' ' . implode( ', ', $parameters ) . ' ' : '' ) . ')'
		. ( '' === $return ? '' : ": {$return}" ) . ';';
}

/**
 * Render the interface carrying the annotations of the given kinds of attributes.
 *
 * @param array<class-string> $only Attributes to restrict the interface to, all of them if empty.
 * @return string
 */
function wp_cli_tests_legacy_interface( array $only = [] ) {
	$methods = [];

	foreach ( ( new ReflectionClass( FeatureContext::class ) )->getMethods( ReflectionMethod::IS_PUBLIC ) as $method ) {
		$annotations = [];

		foreach ( [ Definition::class, Hook::class ] as $kind ) {
			foreach ( $method->getAttributes( $kind, ReflectionAttribute::IS_INSTANCEOF ) as $attribute ) {
				if ( $only && ! in_array( $attribute->getName(), $only, true ) ) {
					continue;
				}

				// Public properties in every Behat version, which the getters are not.
				$values   = get_object_vars( $attribute->newInstance() );
				$argument = $values['pattern'] ?? $values['filterString'] ?? null;
				$name     = substr( (string) strrchr( $attribute->getName(), '\\' ), 1 );

				if ( null !== $argument && ( false !== strpos( $argument, '*/' ) || false !== strpos( $argument, "\n" ) ) ) {
					throw new RuntimeException( "The argument of #[{$name}] on {$method->getName()}() cannot be written as an annotation." );
				}

				$annotations[] = "\t * @{$name}" . ( null === $argument || '' === $argument ? '' : " {$argument}" );
			}
		}

		if ( $annotations ) {
			$methods[] = "\t/**\n" . implode( "\n", $annotations ) . "\n\t */\n\t" . wp_cli_tests_legacy_signature( $method ) . "\n";
		}
	}

	return "<?php\n\n"
		. "// Generated by utils/generate-legacy-annotations.php from the attributes of the contexts, do not edit.\n\n"
		. "namespace WP_CLI\\Tests\\Context;\n\n"
		. "interface LegacyAnnotations {\n\n"
		. implode( "\n", $methods )
		. "}\n";
}

/**
 * The generated files and their contents.
 *
 * @return array<string, string>
 */
function wp_cli_tests_legacy_files() {
	$dir = dirname( __DIR__ ) . '/src/Context/legacy';

	return [
		"{$dir}/annotations.php"            => wp_cli_tests_legacy_interface(),
		"{$dir}/suite-hook-annotations.php" => wp_cli_tests_legacy_interface( [ BeforeSuite::class, AfterSuite::class ] ),
	];
}

if ( isset( $argv[0] ) && realpath( $argv[0] ) === __FILE__ ) {
	require dirname( __DIR__ ) . '/vendor/autoload.php';

	$wp_cli_tests_check = in_array( '--check', $argv, true );
	$wp_cli_tests_stale = false;

	foreach ( wp_cli_tests_legacy_files() as $wp_cli_tests_file => $wp_cli_tests_contents ) {
		if ( file_exists( $wp_cli_tests_file ) && file_get_contents( $wp_cli_tests_file ) === $wp_cli_tests_contents ) {
			continue;
		}

		$wp_cli_tests_stale = true;

		if ( $wp_cli_tests_check ) {
			fwrite( STDERR, "{$wp_cli_tests_file} is out of date, run `php utils/generate-legacy-annotations.php`.\n" );
		} else {
			file_put_contents( $wp_cli_tests_file, $wp_cli_tests_contents );
			echo "Wrote {$wp_cli_tests_file}\n";
		}
	}

	exit( $wp_cli_tests_check && $wp_cli_tests_stale ? 1 : 0 );
}
